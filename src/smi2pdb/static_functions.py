"""PDB export and job-directory helpers for smi2pdb 2.0.0."""
from pathlib import Path
import math
from . import __version__


def next_job_number(directory="output/"):
    root = Path(directory)
    if not root.exists():
        return 1
    return max((int(p.name) for p in root.iterdir() if p.name.isdigit()), default=0) + 1


def write_to_pdb(mol_list, box_dimensions, output_file):
    """Write orthogonal cell, atom/residue identities and bond connectivity.

    Reject sizes that would overflow standard PDB fields. Packing uses these
    same three-decimal coordinates and box dimensions for its clash checks.
    """
    atom_count = sum(m.mol_obj.GetNumAtoms() for m in mol_list)
    if atom_count > 99999 or len(mol_list) > 9999:
        raise ValueError("System exceeds standard PDB limits (99999 atoms / 9999 molecules).")
    if any(not math.isfinite(v) or v <= 0 or len(f"{v:9.3f}") > 9 for v in box_dimensions):
        raise ValueError("Box dimensions cannot be represented in PDB CRYST1 fields.")
    for molecule in mol_list:
        for position in molecule.mol_obj.GetConformer().GetPositions():
            if any(not math.isfinite(v) or len(f"{v:8.3f}") > 8 for v in position):
                raise ValueError("Atomic coordinates exceed standard PDB field limits.")
    a, b, c = box_dimensions
    with Path(output_file).open("w", encoding="ascii") as stream:
        stream.write(f"REMARK   Generated by smi2pdb {__version__}; scaled vdW clash rejection\n")
        stream.write(f"CRYST1{a:9.3f}{b:9.3f}{c:9.3f}{90:7.2f}{90:7.2f}{90:7.2f} P 1           1\n")
        serial = 1
        connectivity = []
        for residue, molecule in enumerate(mol_list, start=1):
            mol = molecule.mol_obj
            conf = mol.GetConformer()
            first_serial = serial
            for atom in mol.GetAtoms():
                x, y, z = conf.GetAtomPosition(atom.GetIdx())
                symbol = atom.GetSymbol()
                atom_name = f" {symbol:<3}" if len(symbol) == 1 else f"{symbol:<4}"
                stream.write(
                    f"HETATM{serial:5d} {atom_name} LIG A{residue:4d}    "
                    f"{x:8.3f}{y:8.3f}{z:8.3f}{1:6.2f}{0:6.2f}          {symbol:>2}  \n"
                )
                serial += 1
            for atom in mol.GetAtoms():
                neighbours = [first_serial + other.GetIdx() for other in atom.GetNeighbors()]
                for offset in range(0, len(neighbours), 4):
                    connectivity.append(
                        f"CONECT{first_serial + atom.GetIdx():5d}"
                        + "".join(f"{n:5d}" for n in neighbours[offset:offset + 4]) + "\n"
                    )
        stream.writelines(connectivity)
        stream.write("END\n")
